import { Router } from 'express';
import { z } from 'zod';
import { createProduct, getApprovedProducts, getProductById, getSellerProducts, getPendingProducts, updateProduct, approveProduct, rejectProduct, deleteProduct } from '../controllers/product.controller.js';
import { protect } from '../middleware/auth.middleware.js';
import { requireRole } from '../middleware/role.middleware.js';
import { validate } from '../middleware/validate.middleware.js';
const router = Router();
const productData = z.object({ title: z.string().trim().min(2).max(120), description: z.string().trim().min(8).max(3000), price: z.coerce.number().positive().max(1000000), category: z.string().trim().min(2).max(60), stock: z.coerce.number().int().min(0).max(100000), imageUrl: z.string().trim().url().max(500).or(z.literal('')).optional() });
const productPatch = productData.partial().refine((data) => Object.keys(data).length > 0);
router.get('/', getApprovedProducts);
router.get('/mine', protect, requireRole(['seller', 'admin']), getSellerProducts);
router.get('/pending', protect, requireRole(['admin']), getPendingProducts);
router.get('/:id', getProductById);
router.post('/', protect, requireRole(['seller', 'admin']), validate(productData), createProduct);
router.patch('/:id', protect, requireRole(['seller', 'admin']), validate(productPatch), updateProduct);
router.post('/:id/approve', protect, requireRole(['admin']), approveProduct);
router.post('/:id/reject', protect, requireRole(['admin']), rejectProduct);
router.delete('/:id', protect, requireRole(['seller', 'admin']), deleteProduct);
export default router;
